const fs=require('fs');
const vm=require('vm');
const assert=require('assert/strict');
const html=fs.readFileSync(process.argv[2],'utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
const source=scripts[scripts.length-1][1];
const payload=html.match(/<script id="payload" type="application\/json">([\s\S]*?)<\/script>/)[1];
const fixture=JSON.parse(payload);
fixture.layers={static:[[0,0,0]],road:[[0,1,0]],carla:[[0,2,0]]};
fixture.ego_history=[0,1,2].map(i=>({frame_id:i,timestamp:100+i*.2,position:[i*4,0,0],yaw:i*45}));
fixture.objects={'7':{history:[{timestamp:100,position:[1,2,0],rotation:{yaw:0},dimensions:{length:4,width:2,height:1},motion_status:'PARKED_CANDIDATE'}],trajectory:[]}};
const paths=[],labels=[],dots=[];
let current=[],fillColor='';
const ctx={setTransform(){},clearRect(){paths.length=0;labels.length=0;dots.length=0;},save(){},restore(){},setLineDash(){},beginPath(){current=[];},moveTo(...p){current.push(p);},lineTo(...p){current.push(p);},closePath(){},stroke(){},fill(){paths.push(current.slice());},fillRect(...p){dots.push({color:fillColor,coords:p});},fillText(text,...p){labels.push({text,color:fillColor,coords:p});},set fillStyle(v){fillColor=v;},get fillStyle(){return fillColor;}};
const elements={payload:{textContent:JSON.stringify(fixture)},mode:{value:'bev'},time:{value:'0'},timeValue:{}};
for(const id of ['showCarla','showLVIMOT','showVehicles','showEgo'])elements[id]={checked:true};
for(const value of Object.values(elements))value.addEventListener=()=>{};
elements.view={clientWidth:900,clientHeight:650,getContext:()=>ctx,addEventListener(){},setPointerCapture(){}};
const sandbox={document:{getElementById:id=>elements[id]},window:{devicePixelRatio:1,addEventListener(){}},requestAnimationFrame(fn){fn();}};
vm.createContext(sandbox);vm.runInContext(source,sandbox,{filename:'offline_map.js'});
const first=JSON.parse(JSON.stringify(paths[0]));
assert.equal(labels.filter(x=>x.text==='EGO').length,1);
assert.equal(labels.find(x=>x.text==='ID 7').color,'#238636');
assert.equal(elements.timeValue.textContent,'0.0 s');
elements.time.value='1000';vm.runInContext('draw()',sandbox);
assert.notDeepEqual(paths[0],first);
assert.equal(elements.timeValue.textContent,'0.4 s');
const end=JSON.parse(JSON.stringify(paths[0]));
elements.time.value='0';vm.runInContext('draw()',sandbox);
assert.deepEqual(JSON.parse(JSON.stringify(paths[0])),first);
elements.time.value='1000';elements.showVehicles.checked=false;vm.runInContext('draw()',sandbox);
assert(labels.some(x=>x.text==='EGO'));assert(!labels.some(x=>x.text==='ID 7'));
assert.deepEqual(JSON.parse(JSON.stringify(paths[0])),end);
elements.showVehicles.checked=true;elements.showLVIMOT.checked=false;vm.runInContext('draw()',sandbox);
assert(labels.some(x=>x.text==='ID 7'));assert(labels.some(x=>x.text==='EGO'));
assert(dots.every(x=>x.color==='#7d6df2'));
elements.showCarla.checked=false;elements.showEgo.checked=false;vm.runInContext('draw()',sandbox);
assert(!labels.some(x=>x.text==='EGO'));assert(labels.some(x=>x.text==='ID 7'));assert.equal(dots.length,0);
fixture.objects={};fixture.ego_history=[];elements.payload.textContent=JSON.stringify(fixture);
const emptySandbox={...sandbox};vm.createContext(emptySandbox);vm.runInContext(source,emptySandbox);
assert.equal(elements.timeValue.textContent,'0.0 s');
console.log(JSON.stringify({passed:8,checks:['green confirmed IDs','ego time range','marker moves','slider reversal','ego independent of vehicles','vehicles independent of LVIMOT map','CARLA independent toggle','no-history fallback']}));
